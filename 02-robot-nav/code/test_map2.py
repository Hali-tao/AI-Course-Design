START_POS = (12, 12)  # 对应红色 'S' 块中心
END_POS = (12, 23)    # 对应灰色 'E' 块中心


# =====================================================================
# 3. 矩阵精准复现验证程序 (运行此脚本可直接核对生成的网格)
# =====================================================================
def verify_and_draw_map(matrix, start, end):
    grid = np.array(matrix)
    rows, cols = grid.shape
    
    # 构建学术 RGB 显示画布
    display_img = np.ones((rows, cols, 3))
    display_img[grid == 1] = [0.2, 0.4, 0.8]  # 蓝色障碍物对齐
    
    fig, ax = plt.subplots(figsize=(10, 10))
    ax.imshow(display_img, extent=[0, cols, rows, 0])
    
    # 标出起点和终点
    ax.text(start[1]+0.5, start[0]+0.5, 'S', va='center', ha='center', color='white', weight='bold', fontsize=14, bbox=dict(facecolor='red', edgecolor='none'))
    ax.text(end[1]+0.5, end[0]+0.5, 'E', va='center', ha='center', color='black', weight='bold', fontsize=14, bbox=dict(facecolor='lightgray', edgecolor='none'))
    
    # 严格匹配原图的 Grid 排版
    ax.set_xticks(range(cols + 1))
    ax.set_yticks(range(rows + 1))
    ax.grid(True, color='gray', linestyle='-', linewidth=0.5)
    
    # 调整坐标轴标签，使其每格递增 1 且完美贴合原图
    ax.set_xticklabels(range(cols + 1))
    ax.set_yticklabels(range(rows + 1))
    
    plt.title("25 x 25 High-Difficulty Map Grid Reconstruction Verification", fontsize=12, pad=15)
    plt.tight_layout()
    plt.show()

if __name__ == "__main__":
    # 执行验证绘图
    verify_and_draw_map(MAP_GRID_25X25, START_POS, END_POS)